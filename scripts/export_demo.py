"""Export the demo story (both endings) and the benchmark for the static web page.

  python3 scripts/export_demo.py           # uses whatever LLM your .env configures, else the keyword rule
  python3 scripts/export_demo.py --stub    # deterministic: keyword rule only, no network
  python3 scripts/export_demo.py --out somewhere/data.js

Writes web/data.js (window.DEMO = {...}) so web/index.html works from disk and from any static host.
Every number on the page comes from this file; nothing is typed into the HTML by hand.
"""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from benchmark import LABEL, ORDER  # noqa: E402
from treasury import load_evidence, load_policy, load_scenario  # noqa: E402
from treasury.signals import keyword_signal, propose_signal  # noqa: E402
from treasury.story import build_story  # noqa: E402

EMAIL = ("Hi, our internal approval has been delayed and we won't be able to release the USD 8,000 "
         "payment this week. Likely next month. Sorry for the trouble.")


def main() -> None:
    policy = load_policy(ROOT / "policy.json")
    scenario = load_scenario(ROOT / "scenario.json")
    evidence = load_evidence(ROOT / "evidence.json")
    receipt = scenario.receipts[0]
    if "--stub" in sys.argv:
        sig = keyword_signal(EMAIL, receipt.confidence)
    else:
        sig = propose_signal(EMAIL, receipt.confidence, receipt)
    pinned = lambda *_a, **_k: sig  # noqa: E731  both endings see the same email reading

    bench = json.loads((ROOT / "results" / "benchmark.json").read_text())
    data = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "signal_source": sig.source,
        "stories": {path: build_story(scenario, policy, EMAIL, evidence, path, signal=pinned)
                    for path in ("person", "remittance")},
        "policy": {"tiers": [t.__dict__ for t in policy.tiers], "penalties": policy.penalties,
                   "spread_bps": policy.spread_bps, "fees": policy.fees,
                   "evidence": policy.evidence.__dict__},
        "benchmark": {"n": bench["n"], "seed": bench["seed"],
                      "rows": [{"key": k, "label": LABEL[k], **bench["summary"][k]} for k in ORDER],
                      "paired": bench["paired_agent_vs_eager"]},
    }
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else ROOT / "web" / "data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// generated by scripts/export_demo.py; do not edit by hand\nwindow.DEMO = "
                   + json.dumps(data, indent=1) + ";\n")
    print(f"wrote {out} (signal source: {sig.source}, confidence "
          f"{receipt.confidence:.2f} -> {sig.confidence:.2f})")


if __name__ == "__main__":
    main()
