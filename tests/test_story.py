import subprocess
import sys
from pathlib import Path

import pytest

from treasury import load_evidence, load_policy, load_scenario
from treasury.signals import keyword_signal
from treasury.story import build_story

ROOT = Path(__file__).resolve().parent.parent
EMAIL = "Our internal approval has been delayed and we won't be able to release the payment this week. Likely next month."


def story(path):
    return build_story(load_scenario(ROOT / "scenario.json"), load_policy(ROOT / "policy.json"), EMAIL,
                       load_evidence(ROOT / "evidence.json"), path, signal=lambda e, c, r: keyword_signal(e, c))


def actions(step):
    return {d["id"]: d["action"] for d in step["plan"]["decisions"]}


@pytest.mark.parametrize("path", ["person", "remittance"])
def test_both_endings_keep_the_floor_and_pay_the_supplier_after_settlement(path):
    steps = {s["key"]: s for s in story(path)["steps"]}
    assert actions(steps["revised"])["supplier"] == "ESCALATE"
    assert actions(steps["deposit"])["supplier"] == "EXECUTE_NOW"
    assert steps["final"]["floor_ok"] and "supplier" in steps["final"]["executed"]
    assert all(s["cash"]["headroom"] >= 0 for s in steps.values())
    assert "INV-1042" in [r[0] for r in steps["evidence"]["corroboration"]["rejected"]]


def test_remittance_ending_schedules_the_supplier_without_a_person():
    steps = {s["key"]: s for s in story("remittance")["steps"]}
    assert "person" not in steps
    assert actions(steps["bank"])["supplier"] == "SCHEDULE_ON_DEPOSIT"
    assert "EXECUTE_NOW" not in actions(steps["bank"]).values()      # R1: corroborated is not settled


def test_initial_plan_is_shown_with_the_bills_it_paid():
    steps = {s["key"]: s for s in story("person")["steps"]}
    assert steps["plan"]["executed"] == ["freight"] and "freight" in actions(steps["plan"])


def test_unknown_path_is_rejected():
    with pytest.raises(ValueError):
        story("magic")


def test_export_writes_page_data_offline(tmp_path):
    dest = tmp_path / "data.js"
    out = subprocess.run([sys.executable, "scripts/export_demo.py", "--stub", "--out", str(dest)], cwd=ROOT,
                         capture_output=True, text=True)
    assert out.returncode == 0, out.stderr
    text = dest.read_text()
    assert text.startswith("// generated by scripts/export_demo.py") and '"remittance"' in text
